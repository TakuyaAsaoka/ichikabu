const closedDays: ReadonlySet<string> = new Set(CLOSED_DAYS);

/** 権利日を計算できる年。休場日リストに載っている年から導く（手で二重に持たない） */
export const RIGHTS_YEARS: readonly number[] = [
  ...new Set(CLOSED_DAYS.map((day) => Number(day.slice(0, 4)))),
].sort((a, b) => a - b);

export type RightsDates = {
  /** 権利確定日。決算月の月末営業日 */
  recordDate: string;
  /** 配当落ち日。権利確定日の1営業日前 */
  exDate: string;
  /** 権利付最終日。権利確定日の2営業日前 */
  lastDate: string;
};

const key = (date: Date): string => date.toISOString().slice(0, 10);

/** 営業日か。土日でなく、休場日リストにも無い日 */
const isBusinessDay = (date: Date): boolean => {
  const weekday = date.getUTCDay();
  return weekday !== 0 && weekday !== 6 && !closedDays.has(key(date));
};

/** その日は含めず、遡って最初に見つかる営業日 */
const previousBusinessDay = (date: Date): Date => {
  const day = new Date(date);
  do {
    day.setUTCDate(day.getUTCDate() - 1);
  } while (!isBusinessDay(day));
  return day;
};

/**
 * 決算月の権利確定日・配当落ち日・権利付最終日を求める。
 * 休場日リストに無い年は `null`（推測で埋めると誤った日付を計算結果として出すことになる）。
 *
 * 権利付最終日が権利確定日の2営業日前なのは、日本市場の決済が2019年7月からT+2
 * （約定日の2営業日後に受け渡し）で、権利確定日までに受け渡しが済んでいる必要があるため。
 */
export function rightsDates(
  year: number,
  fiscalMonth: number,
): RightsDates | null {
  if (!RIGHTS_YEARS.includes(year)) return null;

  // 月末日。`Date.UTC` は日に 0 を渡すと前月の末日を指すので、月に fiscalMonth
  // （0起点では翌月）を渡すと決算月の末日になる
  let recordDate = new Date(Date.UTC(year, fiscalMonth, 0));
  if (!isBusinessDay(recordDate)) recordDate = previousBusinessDay(recordDate);

  const exDate = previousBusinessDay(recordDate);
  const lastDate = previousBusinessDay(exDate);
  return {
    recordDate: key(recordDate),
    exDate: key(exDate),
    lastDate: key(lastDate),
  };
}
