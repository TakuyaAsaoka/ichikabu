/**
 * ソースを文字列として読む検査のための下ごしらえ。
 *
 * **コメントを取り除いてから見る。** 決まりを機械で守る検査は、その決まりの文字列
 * （`<select>`・`border-input`・`disabled:opacity-100` など）をソースから探す。
 * ところが決まりを説明したコメントにも同じ文字列が現れるため、取り除かないと
 * 次の2通りで間違える（#161 でどちらも実際に踏んだ）。
 *
 * - **緑のまま通る**: `className` から `border-input` を消しても、
 *   「なぜ渡すか」を書いたコメントが残っていて、検査が見つけてしまう
 * - **正しいコードを赤くする**: 「生の選択欄はやめた」と書いたコメントの中の
 *   小文字のタグを、生の選択欄そのものとして数える
 */

/**
 * コメントを取り除く。
 *
 * **行の途中に書いた `//` も消す。** 行まるごとだけにすると、
 * `className="..." // このクラスは要らない` の形が残り、クラス名を渡したかを
 * 見る検査に逃げ道ができる。
 *
 * ただし直前が `:` のものは残す。文字列の中のURL
 * （`app/bulk-event-form.tsx` の見本にある `https://...`）がそれで、
 * 消すとそこから行末までが一緒に消える。
 *
 * 塊のコメントは JSX の中に書いたもの（中括弧で包んだもの）も消すが、
 * 中括弧そのものは残るので、括弧の対応を数える側は崩れない
 */
export function stripComments(source: string): string {
  return source
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/(^|[^:])\/\/[^\n]*$/gm, "$1");
}
